def install_polling_heartbeat(application):
    original_get_updates = application.bot.get_updates

    async def tracked_get_updates(*args, **kwargs):
        updates = await original_get_updates(*args, **kwargs)
        temporary_path = f"{POLLING_HEARTBEAT_PATH}.{os.getpid()}.tmp"
        try:
            with open(temporary_path, "w", encoding="ascii") as heartbeat_file:
                heartbeat_file.write(f"{time.time():.6f}\n")
            os.chmod(temporary_path, 0o600)
            os.replace(temporary_path, POLLING_HEARTBEAT_PATH)
        except OSError as exc:
            logger.warning("Could not write polling heartbeat: %s", exc)
            try:
                os.unlink(temporary_path)
            except OSError:
                pass
        return updates

    object.__setattr__(application.bot, "get_updates", tracked_get_updates)

